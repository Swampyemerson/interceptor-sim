# --------------------------------------------------------------------------
# board_cells_json -- the exact per-cell bit layout, asked from cv2 itself.
# --------------------------------------------------------------------------

def board_cells_json(square_len=1.0):
    """The ADOPTED board's per-cell layout: black-square vs marker-square,
    and for marker cells the marker id + the exact (border-included) bit
    matrix cv2.aruco.CharucoBoard.generateImage() actually renders there.

    This is the SOURCE OF TRUTH `scripts/bench/calib_pattern.html` draws from
    (its inline JS embeds this dict verbatim) -- see the module docstring.
    Returns None if this cv2 build has no cv2.aruco (checkerboard fallback;
    calib_pattern.html has nothing to embed in that case, and the fallback
    board is a plain printable/drawable checkerboard instead)."""
    if not HAS_ARUCO:
        return None
    dictionary = cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, ARUCO_DICT))
    board = cv2.aruco.CharucoBoard((SQUARES_X, SQUARES_Y), square_len,
                                    square_len * MARKER_RATIO, dictionary)
    ids = board.getIds().flatten().tolist()
    cell_px = GEN_CELL_PX
    w, h = SQUARES_X * cell_px, SQUARES_Y * cell_px
    img = board.generateImage((w, h), marginSize=0, borderBits=BORDER_BITS)
    marker_total_px = MARKER_RATIO * cell_px
    bit_px = marker_total_px / CELL_BITS

    # Every candidate (marker id, rotation) bit pattern, sampled the same way
    # the board image is sampled below, so a match is a real pixel-level match.
    candidates = {}
    for mid in range(dictionary.bytesList.shape[0]):
        base = dictionary.generateImageMarker(mid, CELL_BITS * 40,
                                               borderBits=BORDER_BITS)
        step = base.shape[0] / CELL_BITS
        bits = np.zeros((CELL_BITS, CELL_BITS), dtype=np.uint8)
        for r in range(CELL_BITS):
            for c in range(CELL_BITS):
                y = int((r + 0.5) * step)
                x = int((c + 0.5) * step)
                bits[r, c] = 1 if base[y, x] > 127 else 0
        for rot in range(4):
            candidates[(mid, rot)] = np.rot90(bits, rot)

    cells = []
    for row in range(SQUARES_Y):
        for col in range(SQUARES_X):
            y0, x0 = row * cell_px, col * cell_px
            cell = img[y0:y0 + cell_px, x0:x0 + cell_px]
            if float((cell < 128).mean()) > 0.9:
                cells.append({"row": row, "col": col, "type": "black"})
                continue
            margin_px = (cell_px - marker_total_px) / 2.0
            my0, mx0 = y0 + margin_px, x0 + margin_px
            bits = np.zeros((CELL_BITS, CELL_BITS), dtype=np.uint8)
            for r in range(CELL_BITS):
                for c in range(CELL_BITS):
                    yy = int(my0 + (r + 0.5) * bit_px)
                    xx = int(mx0 + (c + 0.5) * bit_px)
                    bits[r, c] = 1 if img[yy, xx] > 127 else 0
            match = None
            for (mid, rot), cbits in candidates.items():
                if np.array_equal(bits, cbits):
                    match = (mid, rot)
                    break
            if match is None:
                raise RuntimeError(
                    f"board_cells_json: no dictionary match for cell "
                    f"row={row} col={col} -- the board geometry changed "
                    f"without regenerating calib_pattern.html's embedded JSON")
            mid, _rot = match
            cells.append({"row": row, "col": col, "type": "marker", "id": mid,
                          "bits": bits.tolist()})
    return {"dict": ARUCO_DICT, "squaresX": SQUARES_X, "squaresY": SQUARES_Y,
            "squareLength": square_len, "markerLength": square_len * MARKER_RATIO,
            "borderBits": BORDER_BITS, "bitsN": BITS_N, "cellBits": CELL_BITS,
            "ids": ids, "cells": cells}


# --------------------------------------------------------------------------
# Board adapters -- detection only; ChArUco primary, checkerboard fallback.
