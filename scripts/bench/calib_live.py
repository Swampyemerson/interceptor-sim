def _open_source(args):
    src = args.source
    if src.startswith("dir="):
        return iter_dir(cv2, src[len("dir="):], args.auto or 0, 30.0)
    if src.startswith("v4l2"):
        device = src.split("=", 1)[1] if "=" in src else 0
        return iter_v4l2(cv2, device, args.width, args.height, args.exposure_us,
                         args.gain, 0, None)
    if src == "picamera2":
        return iter_picamera2(cv2, args.width, args.height, args.exposure_us,
                              args.gain, 0, None)
    raise SystemExit(f"{LOG} unknown --source {src!r} "
                     f"(use picamera2, dir=PATH, or v4l2[=DEVICE])")


def run(args):
    adapter = make_adapter(args.square_mm)
    if adapter.kind == "charuco":
        print(f"{LOG} board: ChArUco {SQUARES_X}x{SQUARES_Y} squares, "
              f"square={args.square_mm:.2f} mm ({ARUCO_DICT})")
    else:
        print(f"{LOG} board: checkerboard {CB_COLS}x{CB_ROWS} inner corners, "
              f"square={args.square_mm:.2f} mm")
    cov = Coverage()
    state = SharedState()
    _server, _t = start_server(state, args.host, args.port)
    print(f"{LOG} serving http://{args.host}:{args.port} -- watch it on your phone")
    print(f"{LOG} goal: >= {args.min_views} views, all {N_REGIONS} frame regions, "
          f"all {len(TILT_BINS)} tilt bins")

    k_guess = approx_k_guess(args.width, args.height)
    gen = _open_source(args)
    image_size = None
    n_seen = 0
    try:
        for fr in gen:
            n_seen += 1
            gray = fr.gray
            if gray is None:
                continue
            if image_size is None:
                image_size = (gray.shape[1], gray.shape[0])
            result = consider_frame(gray, adapter, cov, k_guess,
                                     args.min_sharpness, args.max_per_bucket)
            status = {
                "n_kept": cov.saved, "min_views": args.min_views,
                "regions_filled": cov.regions_filled, "n_regions": N_REGIONS,
                "region_counts": list(cov.region_counts),
                "region_names": list(REGION_NAMES),
                "tilt_counts": list(cov.tilt_counts), "tilt_names": list(TILT_BINS),
                "rejected_no_board": cov.rejected_no_board,
                "rejected_blur": cov.rejected_blur,
                "rejected_redundant": cov.rejected_redundant,
                "instruction": instruction_for(cov, args.min_views),
                "ready": cov.is_ready(args.min_views), "done": False,
            }
            state.set_status(status)
            ok_enc, buf = cv2.imencode(".jpg", _annotate(gray, result),
                                       [cv2.IMWRITE_JPEG_QUALITY, 70])
            if ok_enc:
                state.set_frame(buf.tobytes())
            if result.get("kept"):
                print(f"{LOG} KEPT {cov.saved}/{args.min_views}  "
                      f"region={REGION_NAMES[result['region']]} "
                      f"tilt={TILT_BINS[result['tilt']]} "
                      f"({result['tilt_deg']:.0f} deg)  sharp={result['sharpness']:.0f}  "
                      f"regions={cov.regions_filled}/{N_REGIONS} "
                      f"tilts={cov.tilts_filled}/{len(TILT_BINS)}")
            if cov.is_ready(args.min_views):
                break
            if args.auto and n_seen >= args.auto:
                break
    except KeyboardInterrupt:
        print(f"\n{LOG} interrupted -- reporting what was captured so far.")
    finally:
        try:
            gen.close()
        except Exception:
            pass

    ready = cov.is_ready(args.min_views)
    print(f"{LOG} ---------------- session summary ----------------")
    print(f"{LOG} kept {cov.saved} views (need >= {args.min_views}); "
          f"regions {cov.regions_filled}/{N_REGIONS}; "
          f"tilts {cov.tilts_filled}/{len(TILT_BINS)}")
    if cov.empty_regions():
        print(f"{LOG} EMPTY regions: "
              + ", ".join(REGION_NAMES[i] for i in cov.empty_regions()))
    if cov.empty_tilts():
        print(f"{LOG} EMPTY tilt bins: "
              + ", ".join(TILT_BINS[i] for i in cov.empty_tilts()))
    if not ready or image_size is None:
        print(f"{LOG} VERDICT: NOT READY -- stopped early. Re-run to keep "
              f"filling gaps (this session's views are not saved to disk and "
              f"are not reused across runs).")
        state.set_status({**state.get_status(), "done": True, "ready": False})
        return 1

    obj_list = [v["obj_pts"] for v in cov.views]
    img_list = [v["img_pts"] for v in cov.views]
    rms_p, K_p, dist_p, n_used_p = solve_pinhole(obj_list, img_list, image_size)
    print(f"{LOG} PINHOLE  fx={K_p[0, 0]:.2f} fy={K_p[1, 1]:.2f} "
          f"cx={K_p[0, 2]:.2f} cy={K_p[1, 2]:.2f}  rms={rms_p:.3f}px "
          f"over {n_used_p} views")

    rms_f = None
    fe = solve_fisheye(obj_list, img_list, image_size, adapter.full_n_points)
    if fe is None:
        print(f"{LOG} FISHEYE  skipped (fewer than 4 full-board views -- every "
              f"kept view must see all {adapter.full_n_points} board points; "
              f"partial edge views, which the pinhole solve above DOES use, "
              f"don't qualify)")
    else:
        rms_f, K_f, D_f, n_full = fe
        print(f"{LOG} FISHEYE  fx={K_f[0, 0]:.2f} fy={K_f[1, 1]:.2f} "
              f"cx={K_f[0, 2]:.2f} cy={K_f[1, 2]:.2f}  rms={rms_f:.3f}px "
              f"over {n_full} full-board views")
        if rms_f < rms_p * 0.67:
            print(f"{LOG} NOTE: fisheye RMS is notably lower than pinhole -- "
                  f"this 118 deg lens may be better modeled as fisheye. "
                  f"flight/camera.py's CameraModel only supports pinhole + "
                  f"Brown-Conrady today, so the PINHOLE result is what gets "
                  f"written; treat the fisheye numbers as diagnostic.")
        fpath = os.path.splitext(args.out)[0] + "_fisheye_diagnostic.json"
        with open(fpath, "w") as f:
            json.dump({
                "note": "DIAGNOSTIC ONLY -- flight/camera.py cannot consume "
                        "the fisheye distortion model; this is not read by "
                        "any flight code.",
                "fx": float(K_f[0, 0]), "fy": float(K_f[1, 1]),
                "cx": float(K_f[0, 2]), "cy": float(K_f[1, 2]),
                "dist_coeffs_k1234": [float(x) for x in np.asarray(D_f).flatten()],
                "rms_reproj_error_px": float(rms_f), "n_views": n_full,
            }, f, indent=2)
        print(f"{LOG} wrote {fpath} (diagnostic, not consumed by flight code)")

    out = write_intrinsics_json(args.out, K_p, dist_p, image_size, n_used_p,
                                rms_p, source=f"{adapter.kind}_tv")
    print(f"{LOG} wrote {args.out}")
    if out["rms_reproj_error_px"] > 1.0:
        print(f"{LOG} WARNING: pinhole RMS > 1.0px -- marginal; recapture "
              f"with more spread before trusting ranges.")
    state.set_status({**state.get_status(), "done": True, "ready": True,
                      "rms_pinhole": rms_p, "rms_fisheye": rms_f})
    time.sleep(2)  # let the phone page show the final status before exit
    return 0


