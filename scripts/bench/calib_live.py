class DetectedView:
    __slots__ = ("obj_pts", "img_pts", "draw_corners")

    def __init__(self, obj_pts, img_pts, draw_corners):
        self.obj_pts = obj_pts          # (N,3) float64, board frame, Z=0
        self.img_pts = img_pts          # (N,2) float64, pixel coords
        self.draw_corners = draw_corners  # whatever shape cv2 drew corners in


class CharucoBoardAdapter:
    kind = "charuco"

    def __init__(self, square_mm):
        dictionary = cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, ARUCO_DICT))
        square_m = square_mm / 1000.0
        marker_m = square_m * MARKER_RATIO
        self.board = cv2.aruco.CharucoBoard((SQUARES_X, SQUARES_Y), square_m,
                                             marker_m, dictionary)
        self.board.setLegacyPattern(False)  # explicit; see module docstring
        det_params = cv2.aruco.DetectorParameters()
        det_params.cornerRefinementMethod = cv2.aruco.CORNER_REFINE_SUBPIX
        charuco_params = cv2.aruco.CharucoParameters()
        self.detector = cv2.aruco.CharucoDetector(self.board, charuco_params,
                                                   det_params)
        self.full_n_points = len(self.board.getChessboardCorners())

    def detect(self, gray):
        corners, ids, _mc, _mi = self.detector.detectBoard(gray)
        if corners is None or ids is None or len(corners) < MIN_POINTS_PER_VIEW:
            return None
        obj_pts, img_pts = self.board.matchImagePoints(corners, ids)
        if obj_pts is None or len(obj_pts) < MIN_POINTS_PER_VIEW:
            return None
        return DetectedView(obj_pts.reshape(-1, 3).astype(np.float64),
                            img_pts.reshape(-1, 2).astype(np.float64),
                            draw_corners=corners)


class CheckerboardAdapter:
    kind = "checkerboard"

    def __init__(self, square_mm):
        self.cols, self.rows = CB_COLS, CB_ROWS
        square_m = square_mm / 1000.0
        self.objp = _object_points(self.cols, self.rows, square_m).astype(np.float64)
        self.full_n_points = self.cols * self.rows

    def detect(self, gray):
        corners = _find_corners(gray, self.cols, self.rows)
        if corners is None:
            return None
        img_pts = corners.reshape(-1, 2).astype(np.float64)
        return DetectedView(self.objp.copy(), img_pts, draw_corners=corners)


def make_adapter(square_mm):
    if HAS_ARUCO:
        return CharucoBoardAdapter(square_mm)
    print(f"{LOG} WARNING: this cv2 build has no cv2.aruco -- falling back to "
          f"a plain {CB_COLS}x{CB_ROWS} checkerboard. Partial/edge views will "
          f"NOT count (the whole board must be in frame), so coverage will "
          f"take longer to fill.")
    return CheckerboardAdapter(square_mm)


# --------------------------------------------------------------------------
# Region / tilt classification
# --------------------------------------------------------------------------

def classify_region(u, v, w, h):
    col = min(REGION_COLS - 1, max(0, int(u * REGION_COLS / w))) if w > 0 else REGION_COLS // 2
    row = min(REGION_ROWS - 1, max(0, int(v * REGION_ROWS / h))) if h > 0 else REGION_ROWS // 2
    return row * REGION_COLS + col


def classify_tilt(tilt_deg):
    if tilt_deg < TILT_THRESH_DEG[0]:
        return 0
    if tilt_deg < TILT_THRESH_DEG[1]:
        return 1
    return 2


def approx_k_guess(w, h, hfov_deg=ASSUMED_HFOV_DEG):
    """A rough camera matrix used ONLY to bucket relative pose for the
    coverage map -- never written to any output. See module docstring."""
    fx = (w / 2.0) / math.tan(math.radians(hfov_deg) / 2.0)
    return np.array([[fx, 0.0, w / 2.0], [0.0, fx, h / 2.0], [0.0, 0.0, 1.0]])


def estimate_tilt_deg(obj_pts, img_pts, k_guess):
    """Angle (deg) between the board's pose normal and the camera's OPTICAL
    AXIS (not the line of sight -- see module docstring). None if solvePnP
    fails to converge (never a fabricated 0.0 -- error policy)."""
    ok, rvec, _tvec = cv2.solvePnP(obj_pts.reshape(-1, 1, 3),
                                   img_pts.reshape(-1, 1, 2), k_guess, None)
    if not ok:
        return None
    R, _ = cv2.Rodrigues(rvec)
    c = min(1.0, max(-1.0, abs(float(R[2, 2]))))
    return math.degrees(math.acos(c))


def corners_bbox(draw_corners, w, h, margin=20):
    pts = np.asarray(draw_corners, dtype=float).reshape(-1, 2)
    x0, y0 = float(pts[:, 0].min()), float(pts[:, 1].min())
    x1, y1 = float(pts[:, 0].max()), float(pts[:, 1].max())
    return (max(0, int(x0 - margin)), max(0, int(y0 - margin)),
            min(w, int(x1 + margin)), min(h, int(y1 + margin)))


def sharpness_score(gray, bbox=None):
    if bbox is not None:
        x0, y0, x1, y1 = bbox
        if x1 <= x0 or y1 <= y0:
            return 0.0
        roi = gray[y0:y1, x0:x1]
    else:
        roi = gray
    if roi.size == 0:
        return 0.0
    return float(cv2.Laplacian(roi, cv2.CV_64F).var())


# --------------------------------------------------------------------------
# Coverage bookkeeping + keep decision
# --------------------------------------------------------------------------

class Coverage:
    def __init__(self):
        self.region_counts = [0] * N_REGIONS
        self.tilt_counts = [0] * len(TILT_BINS)
        self.bucket_counts = {}
        self.saved = 0
        self.rejected_no_board = 0
        self.rejected_blur = 0
        self.rejected_redundant = 0
        self.views = []

    def add(self, region, tilt, view):
        self.region_counts[region] += 1
        self.tilt_counts[tilt] += 1
        self.bucket_counts[(region, tilt)] = self.bucket_counts.get((region, tilt), 0) + 1
        self.saved += 1
        self.views.append(view)

    @property
    def regions_filled(self):
        return sum(1 for c in self.region_counts if c > 0)

    @property
    def tilts_filled(self):
        return sum(1 for c in self.tilt_counts if c > 0)

    def empty_regions(self):
        return [i for i, c in enumerate(self.region_counts) if c == 0]

    def empty_tilts(self):
        return [i for i, c in enumerate(self.tilt_counts) if c == 0]

    def is_ready(self, min_views=MIN_VIEWS):
        return (self.saved >= min_views and not self.empty_regions()
                and not self.empty_tilts())


def consider_frame(gray, adapter, cov, k_guess, min_sharpness=DEFAULT_MIN_SHARPNESS,
                    max_per_bucket=MAX_PER_JOINT_BUCKET):
    """Detection + quality/novelty gate on one frame. Never raises on a bad
    frame (fail-soft in a live loop, same convention as
    capture_calib_views.handle_frame). Returns a result dict describing what
    happened -- used both to drive the coverage map and to annotate the live
    view."""
    h, w = gray.shape[:2]
    det = adapter.detect(gray)
    if det is None:
        cov.rejected_no_board += 1
        return {"found": False, "kept": False, "reason": "no board detected"}
    tilt_deg = estimate_tilt_deg(det.obj_pts, det.img_pts, k_guess)
    if tilt_deg is None:
        cov.rejected_no_board += 1
        return {"found": True, "kept": False, "reason": "pose failed"}
    cx, cy = float(det.img_pts[:, 0].mean()), float(det.img_pts[:, 1].mean())
    region = classify_region(cx, cy, w, h)
    tilt = classify_tilt(tilt_deg)
    bbox = corners_bbox(det.draw_corners, w, h)
    sharp = sharpness_score(gray, bbox)
    base = {"found": True, "region": region, "tilt": tilt, "tilt_deg": tilt_deg,
            "sharpness": sharp, "bbox": bbox, "n_pts": len(det.obj_pts)}
    if sharp < min_sharpness:
        cov.rejected_blur += 1
        return {**base, "kept": False,
                "reason": f"too blurry ({sharp:.0f} < {min_sharpness:.0f})"}
    if cov.bucket_counts.get((region, tilt), 0) >= max_per_bucket:
        cov.rejected_redundant += 1
        return {**base, "kept": False,
                "reason": "pose too similar to views already kept"}
    cov.add(region, tilt, {"obj_pts": det.obj_pts, "img_pts": det.img_pts,
                           "n_pts": len(det.obj_pts)})
    return {**base, "kept": True, "reason": "kept"}


def instruction_for(cov, min_views=MIN_VIEWS):
    """One plain-English instruction -- the whole point of the live web page.
    Deterministic order (first empty region, then first empty tilt bin) so it
    does not thrash between two equally-empty cells frame to frame."""
    if cov.is_ready(min_views):
        return "Done -- enough views with full coverage. Solving..."
    empty_r = cov.empty_regions()
    if empty_r:
        return f"put the board in the {REGION_NAMES[empty_r[0]]} of the frame"
    empty_t = cov.empty_tilts()
    if empty_t:
        return TILT_HINT[empty_t[0]]
    remaining = max(0, min_views - cov.saved)
    if remaining > 0:
        return f"keep moving the board around -- {remaining} more view(s) needed"
    return "Done -- enough views with full coverage. Solving..."


