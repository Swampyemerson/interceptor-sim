class SharedState:
    def __init__(self):
        self._lock = threading.Lock()
        self._frame_jpeg = b""
        self._status = {"ready": False, "done": False, "n_kept": 0,
                         "min_views": MIN_VIEWS, "instruction": "starting...",
                         "region_counts": [0] * N_REGIONS, "n_regions": N_REGIONS,
                         "regions_filled": 0, "tilt_counts": [0] * len(TILT_BINS),
                         "tilt_names": list(TILT_BINS), "rejected_no_board": 0,
                         "rejected_blur": 0, "rejected_redundant": 0}

    def set_frame(self, jpeg_bytes):
        with self._lock:
            self._frame_jpeg = jpeg_bytes

    def get_frame(self):
        with self._lock:
            return self._frame_jpeg

    def set_status(self, d):
        with self._lock:
            self._status = dict(d)

    def get_status(self):
        with self._lock:
            return dict(self._status)


class Handler(BaseHTTPRequestHandler):
    state = None  # injected by start_server

    def log_message(self, *_a, **_k):
        pass  # quiet -- this runs on the bench, not for log-watching

    def _send(self, code, ctype, body):
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        try:
            if self.path.startswith("/status.json"):
                self._send(200, "application/json",
                          json.dumps(self.state.get_status()).encode())
            elif self.path.startswith("/frame.jpg"):
                body = self.state.get_frame()
                self._send(200 if body else 503, "image/jpeg", body)
            elif self.path == "/" or self.path.startswith("/index"):
                self._send(200, "text/html", INDEX_HTML.encode())
            else:
                self._send(404, "text/plain", b"not found")
        except (BrokenPipeError, ConnectionResetError):
            pass  # a phone browser navigating away mid-response is normal


def start_server(state, host, port):
    Handler.state = state
    server = ThreadingHTTPServer((host, port), Handler)
    t = threading.Thread(target=server.serve_forever, daemon=True)
    t.start()
    return server, t


def _annotate(gray, result):
    img = cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR)
    if result.get("found") and "bbox" in result:
        x0, y0, x1, y1 = result["bbox"]
        color = (0, 255, 0) if result.get("kept") else (0, 165, 255)
        cv2.rectangle(img, (x0, y0), (x1, y1), color, 2)
    label = "KEPT" if result.get("kept") else ("FOUND" if result.get("found") else "NO BOARD")
    cv2.putText(img, label, (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 1.0,
               (255, 255, 255), 2)
    return img


