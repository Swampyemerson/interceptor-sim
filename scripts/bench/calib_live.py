def main(argv=None):
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--square-mm", type=float,
                    help="square size in mm, read off scripts/bench/calib_pattern.html")
    ap.add_argument("--source", default="picamera2",
                    help="picamera2 (default) | dir=PATH | v4l2[=DEVICE]")
    ap.add_argument("--width", type=int, default=1280)
    ap.add_argument("--height", type=int, default=800)
    ap.add_argument("--exposure-us", type=int, default=CALIB_EXPOSURE_US_DEFAULT,
                    help=f"fixed exposure, microseconds (default "
                         f"{CALIB_EXPOSURE_US_DEFAULT}; spec test range is "
                         f"1000-4000 -- if frames flicker/band from the TV's "
                         f"backlight, retry with 1000/3000/4000)")
    ap.add_argument("--gain", type=float, default=4.0)
    ap.add_argument("--host", default="0.0.0.0")
    ap.add_argument("--port", type=int, default=8000)
    ap.add_argument("--out", default="camera_intrinsics_real.json")
    ap.add_argument("--min-views", type=int, default=MIN_VIEWS)
    ap.add_argument("--max-per-bucket", type=int, default=MAX_PER_JOINT_BUCKET)
    ap.add_argument("--min-sharpness", type=float, default=DEFAULT_MIN_SHARPNESS)
    ap.add_argument("--auto", type=int, default=0, metavar="N",
                    help="stop after N frames regardless of coverage "
                         "(testing / non-interactive dir replay; 0 = unbounded)")
    ap.add_argument("--emit-board-json", action="store_true",
                    help="print the ChArUco board's cell-layout JSON (for "
                         "embedding in calib_pattern.html) and exit; no camera")
    ap.add_argument("--self-test", action="store_true",
                    help="offline checks, no camera/display; exit 0/1")
    args = ap.parse_args(argv)

    if args.self_test:
        return self_test()
    if args.emit_board_json:
        spec = board_cells_json()
        if spec is None:
            print(f"{LOG} this cv2 build has no cv2.aruco -- nothing to emit "
                  f"(the fallback board is a plain checkerboard, drawn "
                  f"directly, not from a JSON table)")
            return 1
        print(json.dumps(spec))
        return 0
    if not args.square_mm:
        ap.error("--square-mm is required (read it off calib_pattern.html), "
                 "or use --self-test / --emit-board-json")
    return run(args)


if __name__ == "__main__":
    sys.exit(main())
