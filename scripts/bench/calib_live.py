def solve_pinhole(obj_list, img_list, image_size):
    """cv2.calibrateCamera can raise a raw `initIntrinsicParams2D` assertion
    if any ONE view's points are too sparse/near-collinear for its internal
    homography-based initial guess -- consider_frame's MIN_POINTS_PER_VIEW
    gate makes this rare, not impossible (a bench session could still bank a
    borderline view). Rather than let one bad view crash the whole ~2-minute
    session at the very end, retry once dropping the sparsest views."""
    def _solve(objs, imgs):
        objp = [np.asarray(o, dtype=np.float32).reshape(-1, 1, 3) for o in objs]
        imgp = [np.asarray(i, dtype=np.float32).reshape(-1, 1, 2) for i in imgs]
        return cv2.calibrateCamera(objp, imgp, image_size, None, None)

    try:
        rms, K, dist, _rv, _tv = _solve(obj_list, img_list)
        return rms, K, dist, len(obj_list)
    except cv2.error as e:
        n_before = len(obj_list)
        keep = [i for i, o in enumerate(obj_list) if len(o) >= MIN_POINTS_PER_VIEW + 4]
        if len(keep) < 5 or len(keep) == n_before:
            raise
        print(f"{LOG} WARNING: cv2.calibrateCamera failed on the full "
              f"{n_before}-view set ({e}); retrying with the "
              f"{len(keep)} least-sparse views only")
        objs2 = [obj_list[i] for i in keep]
        imgs2 = [img_list[i] for i in keep]
        rms, K, dist, _rv, _tv = _solve(objs2, imgs2)
        return rms, K, dist, len(keep)


def _fisheye_flag(name):
    """cv2 exposes the fisheye CALIB_* flags in DIFFERENT places depending on
    the OpenCV build: under cv2.fisheye on the Pi's system OpenCV (4.10.0,
    verified 2026-09-17) and at the top-level cv2.* on this repo's dev .venv
    (5.0.0). Try both rather than assume one -- an AttributeError here would
    otherwise crash the fisheye solve on whichever machine wasn't tested."""
    if hasattr(cv2.fisheye, name):
        return getattr(cv2.fisheye, name)
    return getattr(cv2, name)


def solve_fisheye(obj_list, img_list, image_size, full_n_points):
    """Fit the fisheye (equidistant) model. cv2.fisheye.calibrate requires
    EVERY view to carry the SAME number of points (a real OpenCV binding
    constraint -- see module docstring), so this uses only the kept views
    that saw the board's full corner set; returns None if fewer than 4
    qualify rather than raise."""
    idx = [i for i, o in enumerate(obj_list) if len(o) == full_n_points]
    if len(idx) < 4:
        return None
    objp = np.array([np.asarray(obj_list[i], dtype=np.float64).reshape(1, -1, 3)
                     for i in idx])
    imgp = np.array([np.asarray(img_list[i], dtype=np.float64).reshape(1, -1, 2)
                     for i in idx])
    flags = _fisheye_flag("CALIB_RECOMPUTE_EXTRINSIC") | _fisheye_flag("CALIB_FIX_SKEW")
    try:
        rms, K, D, _rv, _tv = cv2.fisheye.calibrate(objp, imgp, image_size,
                                                    None, None, flags=flags)
    except cv2.error as e:
        print(f"{LOG} fisheye solve FAILED on {len(idx)} full-board views: {e}")
        return None
    return rms, K, D, len(idx)


def write_intrinsics_json(path, K, dist, image_size, n_views, rms, source):
    """Same schema as scripts/calibrate_camera.py's _write_json (kept as a
    separate writer here, not a shared function, so this file never has to
    edit that one -- tests/test_calib_live.py's schema-drift check compares
    the two key sets so they cannot silently diverge)."""
    w, h = image_size
    out = {
        "source": source,
        "resolution": {"width": int(w), "height": int(h)},
        "fx": float(K[0, 0]), "fy": float(K[1, 1]),
        "cx": float(K[0, 2]), "cy": float(K[1, 2]),
        "dist_coeffs": [float(x) for x in np.asarray(dist).flatten()],
        "rms_reproj_error_px": float(rms),
        "n_views": int(n_views),
        "recorded_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }
    with open(path, "w") as f:
        json.dump(out, f, indent=2)
    return out


