def test_primary_ruler_is_centre_interpolated(tmp_path):
    """THE MUTANT-BEARING ASSERTION. The scorer's primary output must equal the
    CENTRE-based INTERPOLATED value, and differ from BOTH the lens-based value
    and the logged-tick value."""
    fl = _scored(_write_fixture(str(tmp_path / "flight.csv")))
    assert fl.pad_source == "pad-calibrated"
    centre = fl.cpa(rescore_cpa.PRIMARY_MODE)
    lens = fl.cpa("lens")

    assert centre["interp_m"] == pytest.approx(EXPECT_CENTRE_INTERP, abs=1e-4)
    assert centre["logged_m"] == pytest.approx(EXPECT_CENTRE_LOGGED, abs=1e-4)
    assert lens["logged_m"] == pytest.approx(EXPECT_LENS_LOGGED, abs=1e-4)
    assert lens["interp_m"] == pytest.approx(EXPECT_LENS_INTERP, abs=1e-4)

    # ... and the three must be mutually distinct, or the test proves nothing
    assert abs(centre["interp_m"] - lens["logged_m"]) > 0.01
    assert abs(centre["interp_m"] - lens["interp_m"]) > 0.01
    assert abs(centre["interp_m"] - centre["logged_m"]) > 0.01
    assert centre["interp_segment"] is not None      # the CPA is BETWEEN ticks
    # the fixture teleports once (pad -> start of the dash), which is exactly
    # what the long-segment guard is for: it must COUNT it and must not let the
    # CPA be claimed on it.
    assert centre["long_segments"] == 1
    assert centre["interp_on_long_segment"] is False


