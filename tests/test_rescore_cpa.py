# --- THE MUTANT ---------------------------------------------------------------


def _load_mutant(tmp_path, old, new, name):
    """Import a source-level MUTATION of rescore_cpa as its own module."""
    src = open(os.path.join(SCRIPTS, "rescore_cpa.py")).read()
    assert old in src, f"mutation target {old!r} not found -- the code moved"
    mpath = tmp_path / f"{name}.py"
    mpath.write_text(src.replace(old, new, 1))
    spec = importlib.util.spec_from_file_location(name, str(mpath))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_mutant_lens_reference_fails(tmp_path):
    """Restore the DEFECT -- point the scorer back at gt_cam_* by collapsing the
    lever arm to zero -- and the primary assertion must FAIL."""
    mut = _load_mutant(tmp_path,
                       "CAM_FWD_M = 0.120\nCAM_LEFT_M = 0.030\nCAM_UP_M = 0.002",
                       "CAM_FWD_M = 0.0\nCAM_LEFT_M = 0.0\nCAM_UP_M = 0.0",
                       "rescore_cpa_mutant_lens")
    p = _write_fixture(str(tmp_path / "flight.csv"))
    fl = mut.Flight(p)
    fl.load()
    centre = fl.cpa(mut.PRIMARY_MODE)
    lens = fl.cpa("lens")
    # the defect's signature: the "centre" ruler IS the lens ruler again
    assert centre["interp_m"] == pytest.approx(lens["interp_m"], abs=1e-9)
    assert centre["interp_m"] != pytest.approx(EXPECT_CENTRE_INTERP, abs=1e-4)
    with pytest.raises(AssertionError):
        assert centre["interp_m"] == pytest.approx(EXPECT_CENTRE_INTERP, abs=1e-4)


def test_mutant_logged_tick_only_fails(tmp_path):
    """Restore the OTHER half of the defect -- take the smallest logged tick
    instead of the true minimum between ticks -- and the primary must FAIL."""
    mut = _load_mutant(tmp_path,
                       "    if not (0.0 < s < 1.0):\n        return None",
                       "    if True:\n        return None",
                       "rescore_cpa_mutant_logged")
    p = _write_fixture(str(tmp_path / "flight.csv"))
    fl = mut.Flight(p)
    fl.load()
    centre = fl.cpa(mut.PRIMARY_MODE)
    assert centre["interp_m"] == pytest.approx(centre["logged_m"], abs=1e-9)
    with pytest.raises(AssertionError):
        assert centre["interp_m"] == pytest.approx(EXPECT_CENTRE_INTERP, abs=1e-4)


