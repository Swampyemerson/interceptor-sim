def test_gate_arms_exist_and_the_legacy_table_reproduces():
    """The acceptance gate itself, run through the shipped entry point."""
    for arm in rescore_cpa.GATE_ARMS:
        if not os.path.exists(os.path.join(REPO_ROOT, arm)):
            pytest.fail(f"gate arm missing: {arm} (the gate cannot be vacuous)")
    ok, notes, results, pooled = rescore_cpa.gate(
        [m for m in rescore_cpa.MODES if m != "exact"])
    assert ok, f"legacy ad-hoc table did not reproduce: {notes}"
    assert pooled["lens"]["logged"]["n"] == 16
    # and the CORRECTED ruler must differ from the published one -- if it does
    # not, the fix is inert.
    assert abs(pooled["centre"]["interp"]["median_hi"]
               - pooled["adhoc-published"]["interp"]["median_hi"]) > 0.05
