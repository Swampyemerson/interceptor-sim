PAD_CAM = (rescore_cpa.CAM_FWD_M, rescore_cpa.CAM_LEFT_M, 0.2290)
PSI_DEG = 90.0                       # body +x, with the pad datum also 90
BASE_Z = 1.0
TGT = (0.0, 0.30, 1.0)
STEP_M = 0.6
X0 = -6.3                            # ticks land on ..., -0.3, +0.3, ...
N_DASH = 17

EXPECT_CENTRE_INTERP = 0.30
EXPECT_CENTRE_LOGGED = math.hypot(0.30, 0.30)
EXPECT_LENS_LOGGED = math.sqrt(0.18 ** 2 + 0.27 ** 2 + 0.002 ** 2)
EXPECT_LENS_INTERP = math.hypot(0.27, 0.002)


def _write_fixture(path, blank_gt=False, drop_column=None):
    """A flight CSV written THROUGH the producer's own writer."""
    header = list(M4.CSV_HEADER)
    if drop_column:
        header.remove(drop_column)
    with open(path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(header)
        rows = []
        t = 0.0
        for _ in range(5):                              # on the pad
            rows.append(("TAKEOFF", PAD_CAM, 0.0))
            t += 0.2
        for i in range(N_DASH):                         # the dash
            bx = X0 + STEP_M * i
            cam = (bx + rescore_cpa.CAM_FWD_M,
                   0.0 + rescore_cpa.CAM_LEFT_M,
                   BASE_Z + rescore_cpa.CAM_UP_M)
            rows.append(("CODED_DASH", cam,
                         BASE_Z - (PAD_CAM[2] - rescore_cpa.CAM_UP_M)))
        # the producer's writer decides the schema, the formatting and the
        # blank-field convention -- this test never formats a number itself.
        buf = []

        class _Sink:
            def writerow(self, row):
                buf.append(row)

        class _F:
            def flush(self):
                pass

        tt = 0.0
        for phase, cam, alt in rows:
            gt_cam = None if blank_gt else cam
            gt_range = (None if blank_gt else
                        math.dist(cam, TGT))
            M4.write_row_m4(
                _Sink(), _F(), tt, phase, "pronav", False, None,
                PSI_DEG, None, None, None, None, None, None, None,
                (0.0, 0.0, 0.0, 0.0), alt,
                gt_cam, None if blank_gt else TGT, gt_range,
            )
            tt += 0.05
        idx = {c: i for i, c in enumerate(M4.CSV_HEADER)}
        for row in buf:
            if drop_column:
                row = [v for i, v in enumerate(row) if i != idx[drop_column]]
            writer.writerow(row)
    return path


def _scored(path, module=rescore_cpa):
    fl = module.Flight(path)
    fl.load()
    return fl


