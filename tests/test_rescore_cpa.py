"""GOLDEN CONTRACT + MUTANT tests for scripts/rescore_cpa.py (issue #8).

  PRODUCER  scripts/m4_intercept.py -- CSV_HEADER and write_row_m4, the module's
            OWN writer. The fixture flight CSV is generated by calling that
            writer on synthetic ticks; it is NEVER hand-typed. Hand-typed
            fixtures are exactly what let both 2026-07-24 schema breaks pass
            every unit test while the real producer/consumer pair returned
            garbage.
  CONSUMER  scripts/rescore_cpa.py -- the standalone CPA re-scorer.

THE FIXTURE GEOMETRY (chosen so all four answers are different, which is the
only way a scorer's reference and its interpolation can both be pinned):

  * body yaw is due world-+x, psi = 90 deg, so the camera lever
    (0.120 fwd, 0.030 left, 0.002 up) lands on world (+0.120, +0.030, +0.002)
  * the airframe centre flies +x through the ticks ... -0.30, +0.30 ...
    (0.6 m apart) at constant y = 0, z = 1.0
  * the target is static at (0.0, 0.30, 1.0)

  => centre, interpolated  = 0.3000 m  (the true CPA, BETWEEN two ticks)
     centre, logged tick   = 0.4243 m  (sqrt(0.30^2 + 0.30^2))
     lens,   logged tick   = 0.3245 m
     lens,   interpolated  = 0.2700 m

THE MUTANT (required by issue #8): re-pointing the scorer at gt_cam_* -- i.e.
zeroing the lever arm so the airframe centre collapses back onto the camera --
must make the primary assertion FAIL. test_mutant_lens_reference_fails runs
that mutation for real (it rewrites the module source, imports the mutant, and
re-runs the assertions), so this file cannot go green on a scorer that silently
kept measuring the lens.

Offline; no sim. Run:
  .venv/bin/python -m pytest tests/test_rescore_cpa.py -v
"""
